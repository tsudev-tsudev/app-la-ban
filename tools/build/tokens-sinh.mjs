// Hàm THUẦN: tokens (object đã parse từ design/tokens.json) -> chuỗi Dart / CSS. Không đọc ghi tệp.
import { docHex } from './mau.mjs';

const THEME = ['light', 'dark'];

/** '#RRGGBB' | '#AARRGGBB' -> 'Color(0xAARRGGBB)'. */
export function mauDart(hex) {
  const s = hex.slice(1).toUpperCase();
  return `Color(0x${s.length === 6 ? 'FF' + s : s})`;
}

/** '#RRGGBB' | '#AARRGGBB' -> '#rrggbb' hoặc 'rgb(r g b / a)' cho CSS. */
export function mauCss(hex) {
  const { r, g, b, a } = docHex(hex);
  if (a === 1) return hex.toLowerCase();
  return `rgb(${r} ${g} ${b} / ${Number(a.toFixed(3))})`;
}

/** 'primaryDeep' -> 'primary-deep'. */
export function kebab(ten) {
  return ten.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
}

function kiemKhoaMau(tokens) {
  const [a, b] = THEME.map((t) => Object.keys(tokens.color[t]).join(','));
  if (a !== b) throw new Error('color.light và color.dark phải có cùng bộ khoá, cùng thứ tự');
}

function bongDart(lop) {
  const ds = lop.map(
    (s) =>
      `BoxShadow(color: ${mauDart(s.color)}, offset: Offset(${s.x}, ${s.y}), blurRadius: ${s.blur}, spreadRadius: ${s.spread})`,
  );
  return `[\n      ${ds.join(',\n      ')},\n    ]`;
}

function bongCss(lop) {
  return lop.map((s) => `${s.x}px ${s.y}px ${s.blur}px ${s.spread}px ${mauCss(s.color)}`).join(', ');
}

export function sinhDart(tokens) {
  kiemKhoaMau(tokens);
  const khoaMau = Object.keys(tokens.color.light);
  const khoaBong = Object.keys(tokens.shadow.light);
  const o = [];
  o.push('// GENERATED by tools/build/tokens.mjs from design/tokens.json - DO NOT EDIT.');
  o.push('// ignore_for_file: public_member_api_docs');
  o.push('');
  o.push("import 'package:flutter/painting.dart';");
  o.push('');
  o.push('/// Bảng màu theo theme (Spec §2.1).');
  o.push('final class LbColors {');
  o.push('  const LbColors({');
  for (const k of khoaMau) o.push(`    required this.${k},`);
  o.push('  });');
  o.push('');
  for (const t of THEME) {
    o.push(`  static const ${t} = LbColors(`);
    for (const k of khoaMau) o.push(`    ${k}: ${mauDart(tokens.color[t][k])},`);
    o.push('  );');
    o.push('');
  }
  for (const k of khoaMau) o.push(`  final Color ${k};`);
  o.push('}');
  o.push('');
  o.push('/// Thang khoảng cách 8pt (chỉ dùng các giá trị này).');
  o.push('abstract final class LbSpacing {');
  for (const [k, v] of Object.entries(tokens.spacing)) o.push(`  static const double ${k} = ${v};`);
  o.push('}');
  o.push('');
  o.push('/// Bo góc thống nhất.');
  o.push('abstract final class LbRadius {');
  for (const [k, v] of Object.entries(tokens.radius)) o.push(`  static const double ${k} = ${v};`);
  o.push('}');
  o.push('');
  o.push('/// Bóng đổ theo theme (neumorphism nhẹ).');
  o.push('final class LbShadows {');
  o.push('  const LbShadows({');
  for (const k of khoaBong) o.push(`    required this.${k},`);
  o.push('  });');
  o.push('');
  for (const t of THEME) {
    o.push(`  static const ${t} = LbShadows(`);
    for (const k of khoaBong) o.push(`    ${k}: ${bongDart(tokens.shadow[t][k])},`);
    o.push('  );');
    o.push('');
  }
  for (const k of khoaBong) o.push(`  final List<BoxShadow> ${k};`);
  o.push('}');
  o.push('');
  o.push('/// Kính mờ (glassmorphism).');
  o.push('final class LbGlass {');
  o.push('  const LbGlass({required this.fill, required this.border});');
  o.push('');
  o.push(`  static const double blur = ${tokens.glass.blur};`);
  for (const t of THEME) {
    o.push(
      `  static const ${t} = LbGlass(fill: ${mauDart(tokens.glass[t].fill)}, border: ${mauDart(tokens.glass[t].border)});`,
    );
  }
  o.push('');
  o.push('  final Color fill;');
  o.push('  final Color border;');
  o.push('}');
  o.push('');
  o.push('/// Kiểu chữ. Telemetry dùng tabular figures để số không nhảy.');
  o.push('abstract final class LbType {');
  o.push(`  static const String fontFamily = '${tokens.font.family}';`);
  o.push("  static const String fontPackage = 'design_system';");
  for (const [k, v] of Object.entries(tokens.type)) {
    const ff = v.tabular ? ', fontFeatures: [FontFeature.tabularFigures()]' : '';
    o.push(
      `  static const ${k} = TextStyle(fontFamily: fontFamily, package: fontPackage, fontSize: ${v.size}, height: ${+(v.height / v.size).toFixed(4)}, fontWeight: FontWeight.w${v.weight}${ff});`,
    );
  }
  o.push('}');
  o.push('');
  o.push('/// Breakpoint theo cạnh rộng (dp): compact < medium <= x < expanded <= x.');
  o.push('abstract final class LbBreakpoint {');
  for (const [k, v] of Object.entries(tokens.breakpoint)) o.push(`  static const double ${k} = ${v};`);
  o.push('}');
  o.push('');
  o.push('/// Thời lượng chuyển động.');
  o.push('abstract final class LbMotion {');
  for (const [k, v] of Object.entries(tokens.motion)) o.push(`  static const Duration ${k} = Duration(milliseconds: ${v});`);
  o.push('}');
  o.push('');
  return o.join('\n');
}

export function sinhCss(tokens) {
  kiemKhoaMau(tokens);
  const bien = (t) => {
    const ds = Object.entries(tokens.color[t]).map(([k, v]) => `--lb-color-${kebab(k)}:${mauCss(v)}`);
    for (const [k, v] of Object.entries(tokens.shadow[t])) ds.push(`--lb-shadow-${k}:${bongCss(v)}`);
    ds.push(`--lb-glass-fill:${mauCss(tokens.glass[t].fill)}`, `--lb-glass-border:${mauCss(tokens.glass[t].border)}`);
    ds.push(`color-scheme:${t}`);
    return ds.join(';');
  };
  const chung = [];
  for (const [k, v] of Object.entries(tokens.spacing)) chung.push(`--lb-space-${k}:${v}px`);
  for (const [k, v] of Object.entries(tokens.radius)) chung.push(`--lb-radius-${k}:${v}px`);
  chung.push(`--lb-glass-blur:${tokens.glass.blur}px`);
  chung.push(`--lb-font-family:${tokens.font.cssFamily}`);
  for (const [k, v] of Object.entries(tokens.type)) {
    chung.push(`--lb-type-${kebab(k)}:${v.weight} ${v.size / 16}rem/${v.height / 16}rem var(--lb-font-family)`);
  }
  for (const [k, v] of Object.entries(tokens.breakpoint)) chung.push(`--lb-bp-${k}:${v}px`);
  for (const [k, v] of Object.entries(tokens.motion)) chung.push(`--lb-motion-${k}:${v}ms`);
  return [
    `:root{${chung.join(';')}}`,
    `:root,[data-theme="light"]{${bien('light')}}`,
    `@media (prefers-color-scheme:dark){:root:not([data-theme="light"]){${bien('dark')}}}`,
    `[data-theme="dark"]{${bien('dark')}}`,
    `.lb-tabular{font-variant-numeric:tabular-nums}`,
    '',
  ].join('\n');
}
