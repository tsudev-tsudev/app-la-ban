export type ChuoiSoc = Chuoi;

export function ngonNgu(lang: string | null | undefined): NgonNgu {
  return (lang ?? '').toLowerCase().startsWith('en') ? 'en' : 'vi';
}

export function chuoi(n: NgonNgu): Chuoi {
  return n === 'en' ? EN : VI;
}

/** Thời điểm theo giờ Việt Nam, định dạng theo ngôn ngữ giao diện. */
export function dinhDangLuc(ms: number | null | undefined, n: NgonNgu): string {
  if (!ms) return '-';
  return new Intl.DateTimeFormat(n === 'en' ? 'en-GB' : 'vi-VN', {
    timeZone: 'Asia/Ho_Chi_Minh',
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
    hour: '2-digit',
    minute: '2-digit',
    second: '2-digit',
  }).format(ms);
}

/** "3 phút trước" / "3 minutes ago" - cột thời gian gọn; giá trị đầy đủ để ở title. */
export function truocDay(ms: number | null | undefined, n: NgonNgu, bayGio = Date.now()): string {
  if (!ms) return '-';
  const giay = Math.round((ms - bayGio) / 1000);
  const rtf = new Intl.RelativeTimeFormat(n === 'en' ? 'en' : 'vi', { numeric: 'auto' });
  const a = Math.abs(giay);
  if (a < 60) return rtf.format(giay, 'second');
  if (a < 3600) return rtf.format(Math.round(giay / 60), 'minute');
  if (a < 86_400) return rtf.format(Math.round(giay / 3600), 'hour');
  return rtf.format(Math.round(giay / 86_400), 'day');
}

export function dinhDangSo(x: number, n: NgonNgu): string {
  return new Intl.NumberFormat(n === 'en' ? 'en-US' : 'vi-VN').format(x);
}
